"""
PassthroughLLM — A BaseLlm that returns pre-generated text from NeMo RL's vLLM.

Instead of calling an external LLM API, this LLM receives text that was already
generated by NeMo RL and converts it into ADK's LlmResponse format (including
tool call parsing).

Architecture:
    NeMo RL (vLLM generate)
        │ raw text
        ▼
    PassthroughLlm.set_response(text)
        │
    ADK Agent calls generate_content_async()
        │
        ├── Return buffered text as LlmResponse
        ├── Parse tool calls (Qwen3 XML format via vLLM parser)
        └── ADK handles tool execution in sandbox
"""

from __future__ import annotations

import asyncio
import json
import logging
import re
from typing import Any, AsyncGenerator

from google.adk.models.base_llm import BaseLlm
from google.adk.models.llm_request import LlmRequest
from google.adk.models.llm_response import LlmResponse
from google.genai import types
from pydantic import ConfigDict

logger = logging.getLogger(__name__)


class PassthroughLlm(BaseLlm):
    """ADK-compatible LLM that returns pre-generated text from NeMo RL.

    Usage:
        llm = PassthroughLlm()
        llm.set_response("Let me check...\n<tool_call>...")
        # ADK agent calls llm.generate_content_async() and gets this text back
    """

    model_config = ConfigDict(arbitrary_types_allowed=True)
    model: str = "passthrough"

    _response_text: str = ""
    _response_ready: asyncio.Event | None = None

    def set_response(self, text: str) -> None:
        """Buffer a response from NeMo RL's vLLM to be returned on next generate call."""
        self._response_text = text
        if self._response_ready is not None:
            self._response_ready.set()

    async def generate_content_async(
        self, llm_request: LlmRequest, stream: bool = False
    ) -> AsyncGenerator[LlmResponse, None]:
        """Return the buffered response as an ADK LlmResponse.

        If no response is buffered yet, waits until set_response() is called.
        """
        # Wait for response if not ready
        if not self._response_text:
            if self._response_ready is None:
                self._response_ready = asyncio.Event()
            self._response_ready.clear()
            await self._response_ready.wait()

        response_text = self._response_text
        self._response_text = ""  # Clear buffer

        # Parse into ADK Parts (text + function calls)
        parts = _parse_response_to_parts(response_text)

        yield LlmResponse(
            content=types.Content(role="model", parts=parts),
            partial=False,
            finish_reason=types.FinishReason.STOP,
        )


def _parse_response_to_parts(response_text: str) -> list[types.Part]:
    """Parse model output into ADK Parts, extracting tool calls.

    Uses vLLM's Qwen3 XML parser for <tool_call> tags.
    Falls back to plain text if no tool calls found.
    """
    if "<tool_call>" not in response_text:
        return [types.Part(text=response_text)]

    parts: list[types.Part] = []

    try:
        from vllm.tool_parsers.qwen3xml_tool_parser import StreamingXMLToolCallParser

        parser = StreamingXMLToolCallParser()
        result = parser.parse_single_streaming_chunks(response_text)

        # Add text content before tool calls
        if result.content:
            parts.append(types.Part(text=result.content))

        # Add function calls
        for tc in result.tool_calls:
            if tc.function and tc.function.name:
                try:
                    args = json.loads(tc.function.arguments) if tc.function.arguments else {}
                except json.JSONDecodeError:
                    args = {"_raw": tc.function.arguments}

                parts.append(
                    types.Part(
                        function_call=types.FunctionCall(
                            id=tc.id or "",
                            name=tc.function.name,
                            args=args,
                        )
                    )
                )
    except Exception as e:
        logger.warning(f"Failed to parse tool calls, returning as plain text: {e}")
        parts = [types.Part(text=response_text)]

    if not parts:
        parts = [types.Part(text=response_text)]

    return parts
